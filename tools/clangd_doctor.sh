if [ "$FAIL_N" -eq 0 ] && [ "$WARN_N" -eq 0 ]; then
    printf '\n  %sAll checks passed.%s\n' "$C_OK" "$C_RST"
    info "If the editor still complains, restart the LSP client and re-run."
elif [ "$FAIL_N" -eq 0 ]; then
