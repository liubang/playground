    info "Warnings are usually stale or version-pinned settings; fix them soon."
else
    printf '\n  %s%d failure(s), %d warning(s).%s\n' "$C_FAIL" "$FAIL_N" "$WARN_N" "$C_RST"
    printf '  %sSuggested order:%s\n' "$C_DIM" "$C_RST"
    step=1
    printf '    %d. fix every item marked "fail" above (clangd configs live outside this repo)\n' "$step"
    step=$((step + 1))
